const SUPPORTED: Lang[] = ["en", "fr", "pt"];

function normalizeLang(code: string | undefined): Lang {
  const base = (code ?? "en").split("-")[0] as Lang;
  return SUPPORTED.includes(base) ? base : "en";
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

interface I18nState {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

export function LanguageSwitcher({ className }: { className?: string }) {
  const { lang, setLang, t } = useI18n();
  return (
    <select
      className={className ?? "lang-pick"}
      value={lang}
      onChange={(e) => setLang(e.target.value as Lang)}
      aria-label={t("lang.label")}
      title={t("lang.label")}
    >
      {LANGUAGES.map((l) => (
        <option key={l.code} value={l.code}>
          {l.short}
        </option>
      ))}
    </select>
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  return <>{children}</>;
}

export function useI18n(): I18nState {
  const { t, i18n: instance } = useTranslation();
  const lang = normalizeLang(instance.resolvedLanguage ?? instance.language);
  return {
    lang,
    setLang: (next: Lang) => {
      void instance.changeLanguage(next);
    },
    t: (key, vars) => t(key, vars as Record<string, unknown>) as string,
  };
}
